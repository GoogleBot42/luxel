def resolve_qemu(explicit: str | None) -> str:
    if explicit:
        cand = explicit
        if os.path.isdir(cand):
            cand = os.path.join(cand, "bin", "qemu-system-xtensa")
        if not os.access(cand, os.X_OK):
            raise Fail(f"--qemu {explicit}: no executable qemu-system-xtensa")
        return cand

    attempts = [
        ["nix", "build", "--no-link", "--print-out-paths", f"{REPO}#qemu-espressif"],
        [
            "nix", "build", "--no-link", "--print-out-paths", "--impure",
            "--expr", f"import {HERE}/qemu-espressif.nix {{}}",
        ],
    ]
    errors = []
    for cmd in attempts:
        p = subprocess.run(cmd, capture_output=True, text=True)
        if p.returncode == 0 and p.stdout.strip():
            out = p.stdout.strip().splitlines()[-1]
            binary = os.path.join(out, "bin", "qemu-system-xtensa")
            if os.access(binary, os.X_OK):
                return binary
            errors.append(f"{out} has no bin/qemu-system-xtensa")
        else:
            errors.append(p.stderr.strip().splitlines()[-1] if p.stderr.strip() else "nix build failed")
    raise Fail("could not resolve qemu-espressif:\n  " + "\n  ".join(errors))


def make_efuse(path: str) -> None:
    p = subprocess.run(
        [sys.executable, os.path.join(HERE, "make-efuse.py"), "-o", path],
        capture_output=True,
        text=True,
    )
    if p.returncode != 0:
        raise Fail(f"make-efuse.py failed:\n{p.stderr}")


def reached_marker(text: str) -> bool:
    """Boot 2 has printed its creds-from-flash line (prefix match: the SSID
    follows and is never spelled out here)."""
    return REBOOT_LINE in text and KILL_PREFIX in text.split(REBOOT_LINE)[-1]


def run_qemu(qemu: str, flash: str, efuse: str, log: str, timeout: float) -> tuple[str, float]:
    """Boot the composed image; return (serial log, wall seconds).

    Marker-driven: returns as soon as boot 2 proves credential inheritance.
    NOTE the flash drive deliberately has no `snapshot=on` — the post-run
    assertions diff the file QEMU wrote.
    """
    cmd = [
        qemu, "-display", "none", "-monitor", "none", "-machine", "esp32",
        "-drive", f"file={flash},if=mtd,format=raw",
        "-drive", f"file={efuse},if=none,format=raw,id=efuse,snapshot=on",
        "-global", "driver=nvram.esp32.efuse,property=drive,value=efuse",
        "-serial", f"file:{log}",
    ]
    open(log, "wb").close()
    start = time.monotonic()
    with open(os.devnull, "rb") as devnull:
        proc = subprocess.Popen(cmd, stdin=devnull, stdout=subprocess.DEVNULL,
                                stderr=subprocess.PIPE)
        text = ""
        outcome = None
        try:
            while True:
                with open(log, "rb") as f:
                    text = f.read().decode("utf-8", "replace")
                if reached_marker(text):
                    outcome = "marker"
                    break
                for m in ABORT_MARKERS:
                    if m in text:
                        outcome = f"abort line: {m.strip()}"
                        if m in ABORT_HINTS:
                            outcome += f"\n  {ABORT_HINTS[m]}"
                        break
                if outcome:
                    break
                if proc.poll() is not None:
                    outcome = f"qemu exited early (rc={proc.returncode})"
                    break
                if time.monotonic() - start > timeout:
                    outcome = f"timeout after {timeout:.0f}s"
                    break
                time.sleep(0.25)
        finally:
            if proc.poll() is None:
                proc.terminate()
                try:
                    proc.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait()
    elapsed = time.monotonic() - start
    with open(log, "rb") as f:
        text = f.read().decode("utf-8", "replace")
    if outcome != "marker":
        stderr = proc.stderr.read().decode("utf-8", "replace") if proc.stderr else ""
        raise Fail(f"boot did not reach the success marker — {outcome}"
                   + (f"\nqemu stderr:\n{stderr.strip()}" if stderr.strip() else ""))
    return text, elapsed


# --------------------------------------------------------------------------
# assertions


class Checks:
    def __init__(self) -> None:
        self.passed: list[str] = []

    def ok(self, what: str) -> None:
        self.passed.append(what)

    def require(self, cond: bool, what: str, detail: str = "") -> None:
        if not cond:
            raise Fail(f"{what}\n  {detail}" if detail else what)
        self.ok(what)

    def line(self, hay: str, needle: str, where: str) -> None:
        self.require(needle in hay, f"serial[{where}]: {needle!r}",
                     f"not found in the {where} section of the log")


def check_serial(log: str, slot: str, ota_len: int, c: Checks) -> None:
    if REBOOT_LINE not in log:
        raise Fail("takeover never reached the table rewrite")
    boot1, boot2 = log.split(REBOOT_LINE, 1)

    c.line(boot1, "takeover: foreign partition table at 0x8000 — installing Luxel layout", "boot1")
    c.line(boot1, INHERIT_PREFIX, "boot1")  # prefix: the SSID follows, unchecked
    c.require("takeover: no WiFi credentials to inherit" not in boot1,
              "serial[boot1]: NVS creds were found (no provisioning-AP fallback)",
              "the takeover found no creds in Pixelblaze's NVS")
    c.require("takeover: no LED wiring to inherit" not in boot1,
              "serial[boot1]: config.json wiring was found (no board-defaults fallback)",
              "the takeover found no wiring in Pixelblaze's spiffs")
    if slot == "app1":
        c.line(boot1, f"takeover: copying {ota_len} B {APP1:#x} → {APP0:#x}", "boot1")
        # copy_region() narrates every 64th sector; the last such line is the
        # progress proof that the whole image went through the verify loop.
        sectors = -(-ota_len // SECTOR)
        total_kib = sectors * SECTOR // 1024
        last = ((sectors - 1) // 64) * 64 * SECTOR // 1024
        c.line(boot1, f"takeover: copied {last}/{total_kib} KiB", "boot1")
    else:
        c.line(boot1, f"takeover: image already in place at {APP0:#x}", "boot1")
    c.line(boot1, f"takeover: Pixelblaze ran at brightness {BRI_255}/255 × limit "
                  f"{MAXBRI_255}/255 → effective {EFF_255}/255", "boot1")
    c.line(boot1, "takeover: wiping config/otadata sectors 0x9000..0x10000", "boot1")
    c.line(boot1, "takeover: WiFi credentials carried over", "boot1")
    c.line(boot1,
           f"takeover: settings carried over ({PIXELS} px, {PROTO_NAME}, order {ORDER_NAME}, "
           f"brightness {BRIGHTNESS}/31, cap {CAP_MA} mA, gamma "
           f"{GAMMA_TENTHS // 10}.{GAMMA_TENTHS % 10})", "boot1")
    c.ok(f"serial[boot1]: {REBOOT_LINE!r}")

    c.line(boot2, "booted from: ota_0", "boot2")
    # A taken-over device runs ota_0 under Luxel's 4 MB table; the first
    # Luxel OTA must go to that table's ota_1 (0x150000), not over the code
    # it is running (Gitea #655).  ota::init prints the choice every boot.
    c.line(boot2, "ota: updates go to ota_1 at 0x150000", "boot2")
    c.require("ota: updates go to ota_0 at" not in boot2,
              "serial[boot2]: the running slot is never the OTA target",
              "ota::init named ota_0 while executing from it")
    # Luxel's `storage` lands on top of PB's spiffs: whatever the map reader
    # makes of that, it is not the current format, and the store is wiped.
    m = FORMAT_LINE.search(boot2)
    c.require(m is not None, "serial[boot2]: 'patterns: format <n> != <cur>, wiping storage'",
              "the pattern store did not announce a wipe of the old spiffs region")
    c.line(boot2, f"(storage @ {LUXEL_STORAGE:#x})", "boot2")
    c.line(boot2, KILL_PREFIX, "boot2")  # prefix: the SSID follows, unchecked


def check_flash(flash: bytes, expected_table: bytes, ota: bytes, slot: str, c: Checks) -> None:
    got = flash[TABLE_OFFSET : TABLE_OFFSET + TABLE_LEN]
    c.require(got == expected_table, "flash: Luxel partition table installed at 0x8000",
              f"first differing byte at {first_diff(got, expected_table)}")

    check_lxcf(flash, c)
    check_lxdv(flash, c)

    got = flash[APP0 : APP0 + len(ota)]
    c.require(got == ota, f"flash: ota_0 (0x10000) holds the {len(ota)} B app image byte-for-byte",
              f"first differing byte at {first_diff(got, ota)}")

    if slot == "app1":
        # The takeover never writes to its source, and nothing else does
        # either: Luxel's `storage` starts at 0x290000, which is exactly
        # where PB's app1 slot ends, so the whole copy source survives.
        got = flash[APP1 : APP1 + len(ota)]
        c.require(got == ota, f"flash: copy source {APP1:#x} left wholly untouched",
                  f"first differing byte at {first_diff(got, ota)}")
        c.require(APP1 + len(ota) <= LUXEL_STORAGE,
                  f"flash: PB's app1 image ends at {APP1 + len(ota):#x}, at or below "
                  f"the new `storage` at {LUXEL_STORAGE:#x}",
                  "the app image has grown into the storage partition")

    # Luxel's `storage` is PB's spiffs region.  Boot 2's pattern store finds
    # no (valid) format marker there, wipes the key area and writes its own
    # — so the region is no longer PB's config data.  That is the proof the
    # NEW table took effect.
    key_area = flash[LUXEL_STORAGE : LUXEL_STORAGE + SECTOR]
    c.require(any(b != 0xFF for b in key_area),
              f"flash: the new `storage` key area at {LUXEL_STORAGE:#x} was "
              "formatted by the pattern store",
              "still erased — did the new table take effect?")

    # 0xC000 is the boot-guard sector (ota.rs GUARD_OFFSET), inside the wiped
    # range but rewritten by boot 2's `boot_guard()` before the takeover check
    # even runs.  So it is NOT erased: expect the record, attempt count 1.
    guard = flash[LXBG_OFFSET : LXBG_OFFSET + 8]
    c.require(guard[0:4] == b"LXBG" and guard[4] == 1 and guard[5] == 0,
              "flash: boot-guard record at 0xC000 (LXBG, 1 attempt, no force-AP)",
              f"got {guard.hex()}")
    # byte 6 is the takeover reboot-to-retry counter (issue #35); a successful
    # takeover wipes the sector, so it must not leak into the final state.
    c.require(guard[6] == 0, "flash: takeover retry counter cleared (guard byte 6)",
              f"got {guard[6]}")

    # 0xD000 is Luxel's otadata.  The takeover wipes it, so the next boot's
    # ESP-IDF second-stage bootloader finds both entries erased, falls back to
    # ota_0 — and *writes the choice back* (`set_actual_ota_seq()`: seq =
    # index + 1, ota_state = ESP_OTA_IMG_VALID, CRC over the seq word).  So
    # "erased" is the wrong expectation here; this is the observed and correct
    # post-fallback state.  0xE000 was PB's otadata — wiped, and still erased.
    ota0 = flash[LUXEL_OTADATA : LUXEL_OTADATA + 32]
    seq, = struct.unpack("<I", ota0[0:4])
    state, crc = struct.unpack("<II", ota0[24:32])
    want_crc = zlib.crc32(ota0[0:4], 0xFFFFFFFF) & 0xFFFFFFFF
    c.require(seq == 1 and state == ESP_OTA_IMG_VALID and crc == want_crc,
              "flash: otadata 0xD000 rewritten by the bootloader as seq=1/VALID (-> ota_0)",
              f"seq={seq} state={state} crc={crc:#010x} want {want_crc:#010x} raw={ota0.hex()}")
    ota1 = flash[LUXEL_OTADATA + SECTOR : LUXEL_OTADATA + SECTOR + 32]
    c.require(ota1 == b"\xff" * 32,
              "flash: otadata entry #1 (0xE000, PB's old otadata) still erased",
              f"got {ota1.hex()}")


def check_lxcf(flash: bytes, c: Checks) -> None:
    """The inherited-credentials record written by config::write_wifi().

    Validity, lengths and checksum ONLY — the ssid/password bytes are real
    and are never decoded, compared or printed."""
    rec = flash[LXCF_OFFSET : LXCF_OFFSET + SECTOR]
    c.require(rec[0:4] == b"LXCF", "flash: LXCF creds record at 0x9000", f"got {rec[0:8].hex()}")
    ver, slen, plen, pad = rec[4], rec[5], rec[6], rec[7]
    c.require(ver == 1 and pad == 0, "flash: LXCF version 1", f"ver={ver} pad={pad}")
    c.require(1 <= slen <= 32, "flash: inherited ssid length in 1..=32", f"got {slen}")
    c.require(plen <= 64, "flash: inherited password length <= 64", f"got {plen}")
    end = 8 + slen + plen
    stored = struct.unpack("<I", rec[end : end + 4])[0]
    want = sum(rec[:end]) & 0xFFFFFFFF  # config.rs: wrapping u32 byte sum
    c.require(stored == want, "flash: LXCF checksum valid",
              f"stored {stored:#010x} want {want:#010x}")
    tail = rec[end + 4 :]
    c.require(tail == b"\xff" * len(tail), "flash: rest of the 0x9000 sector erased",
              f"first non-0xFF at {first_diff(tail, b'\xff' * len(tail))}")


def check_lxdv(flash: bytes, c: Checks) -> None:
    """The inherited-wiring record written by config::write_device() —
    values are the fixture's config.json (see the module docstring).

    Byte 21 is v8's data pin, stored as pin+1 so 0 means "board default"
    (config.rs); PB v3 hardwires its LED pins to this board's default, so
    the takeover stores no override."""
    rec = flash[LXDV_OFFSET : LXDV_OFFSET + SECTOR]
    c.require(rec[0:4] == b"LXDV", "flash: LXDV device-config record at 0xA000",
              f"got {rec[0:8].hex()}")
    ver, bri, proto, sync = rec[4], rec[5], rec[6], rec[7]
    c.require(ver == DEV_VER, f"flash: LXDV version {DEV_VER}", f"ver={ver}")
    pixels = struct.unpack("<I", rec[8:12])[0]
    tz = struct.unpack("<h", rec[12:14])[0]
    order, gamma = rec[14], rec[15]
    cap = struct.unpack("<H", rec[16:18])[0]
    c.require(pixels == PIXELS, f"flash: imported pixel count {PIXELS}", f"got {pixels}")
    c.require(proto == PROTO_CODE,
              f"flash: imported protocol {PROTO_NAME} (code {PROTO_CODE}, PB ledType 2)",
              f"got {proto}")
    c.require(order == ORDER_CODE,
              f"flash: imported color order {ORDER_NAME} (code {ORDER_CODE}, PB colorOrder GRB)",
              f"got {order}")
    c.require(bri == BRIGHTNESS,
              f"flash: imported brightness {BRIGHTNESS}/31 (PB 1.0 × limit 0.5 = {EFF_255}/255)",
              f"got {bri}")
    c.require(cap == CAP_MA, f"flash: power cap {CAP_MA} mA (PB has none)", f"got {cap}")
    c.require(gamma == GAMMA_TENTHS, "flash: gamma 0.0 (PB exposes none)", f"got {gamma}")
    curve, blur, glow = rec[18], rec[19], rec[20]
    c.require(sync == 0 and tz == 0 and rec[22:24] == b"\x00\x00",
              "flash: LXDV non-imported fields at defaults",
              f"sync={sync} tz={tz} pad={rec[22:24].hex()}")
    stored_pin = rec[21]
    c.require(stored_pin == 0,
              "flash: LXDV data pin 0 = board default (PB v3 pins are hardwired)",
              f"got byte {stored_pin} (= GPIO{stored_pin - 1})")
    c.require(curve == 0 and blur == 0 and glow == 0,
              "flash: post-process chain off (PB has no equivalent)",
              f"curve={curve} blur={blur} glow={glow}")
    stored = struct.unpack("<I", rec[24:28])[0]
    want = sum(rec[:24]) & 0xFFFFFFFF  # config.rs: wrapping u32 byte sum
    c.require(stored == want, "flash: LXDV checksum valid",
              f"stored {stored:#010x} want {want:#010x}")
    tail = rec[28:]
    c.require(tail == b"\xff" * len(tail), "flash: rest of the 0xA000 sector erased",
              f"first non-0xFF at {first_diff(tail, b'\xff' * len(tail))}")


def redact(line: str) -> str:
    for p in SECRET_PREFIXES:
        i = line.find(p)
        if i >= 0:
            return line[: i + len(p)] + "<redacted>"
    return line


def first_diff(a: bytes, b: bytes) -> str:
    n = min(len(a), len(b))
    for i in range(n):
        if a[i] != b[i]:
            return f"+{i:#x} ({a[i]:#04x} != {b[i]:#04x})"
    return f"length {len(a)} != {len(b)}"


