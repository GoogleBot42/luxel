#!/usr/bin/env python3
"""Compose → boot → assert the Pixelblaze v3 → Luxel takeover under emulation.

Hardware-free end-to-end test for the `pixelblaze-takeover` flavour of
`firmware/src/takeover.rs` (settings from Pixelblaze's SPIFFS `config.json`
via src/pbfs.rs, WiFi creds from its ESP-IDF NVS via src/pbnvs.rs).  The
exact analogue of `takeover-test.py` (the WLED one): builds a flash image in
the state a real Pixelblaze v3 is in the instant its OTA updater finishes
accepting a Luxel upload, boots it under Espressif's patched QEMU (see
docs/research/qemu-emulation-spike.md), and asserts on both the takeover's
serial narration and the resulting flash bytes.

The image under test is **stock** — the same `nix build .#luxel-fw-pixelblaze-v3`
output that ships.  Nothing here touches firmware source; the QEMU harness is
strictly isolated (CLAUDE.md hard rule).  The small parse/compose helpers are
deliberately DUPLICATED from takeover-test.py rather than shared, so neither
test can regress the other.

What it composes (4 MiB, from ONE gitignored dump — unlike the Athom there is
no separate filesystem image: the config AND the creds already live inside
the stock dump):

    0x000000  PB bootloader + PB partition table @0x8000       (from --stock)
    0x009000  nvs      0x5000  <- WiFi creds (pbnvs)
    0x00E000  otadata  0x2000  two entries, 0xE000 seq=1 / 0xF000 seq=2
    0x010000  app0     0x140000 (--slot app0 drops the OTA image here)
    0x150000  app1     0x140000 <- the Luxel OTA image, "PB just accepted it"
    0x290000  spiffs   0x170000 <- config.json (pbfs); ALSO where Luxel's
                                  `storage` lands after the takeover

The fixture's config: 180 px, ledType 2 (APA102/SK9822-class), colorOrder
GRB (-> Luxel sk9822 order code 4, "brg"), brightness 1.0 × maxBrightness
0.5 -> effective 128/255 -> Luxel 16/31.  No data pin (PB v3 hardwires
DATA=23/CLK=18 = this board's default), no power cap, no gamma.

THE DUMP CONTAINS REAL WIFI CREDENTIALS.  This test never prints, asserts on
or embeds the SSID or password: the serial assertions match PREFIXES of the
lines that carry the SSID, and the flash assertions check the LXCF record's
magic/version/lengths/checksum only.  Keep it that way (--keep leaves the
serial log and flash image in the work dir — treat both as secret).

Two variants:

    --slot app1  (default) the realistic post-upload state.  The dump's own
                 otadata already selects app1 (seq=2 at 0xF000); exercises
                 the full self-copy 0x150000 -> 0x10000.
    --slot app0  the image is already at the destination offset.  The
                 0xF000 entry is erased so the dump's seq=1 at 0xE000 selects
                 app0.  Exercises the "skip the copy" path.

One QEMU invocation covers both boots: the takeover ends in `software_reset()`,
which reboots in-process.  Boot 2 reaches WiFi init and then panics inside the
esp-radio PHY blob (an unmodelled peripheral alias, expected and documented in
the spike), so QEMU is killed the instant boot 2 prints the inheritance proof
(`wifi: creds from flash (` — prefix only, the rest is the SSID); letting it
run on would give `custom_halt` its reboot and a further boot whose
`ota::boot_guard` would rewrite otadata and ruin the flash diff.

Usage:
    nix build .#luxel-fw-pixelblaze-v3 --out-link result-pb
    nix develop -c python3 tools/qemu/pb-takeover-test.py \
        --stock /path/to/pb-v3-stock.bin --result-dir result-pb

    tools/qemu/pb-takeover-test.py --slot app0 --keep

`--qemu` defaults to auto-resolving the emulator through nix (the flake's
`qemu-espressif` output, falling back to the `--impure` expression path).
The eFuse image is generated by `tools/qemu/make-efuse.py`.

Exit 0 with a PASS summary listing every assertion; nonzero on the first
failure, with a tail of the serial log (which may contain the SSID — it is
the firmware's own narration, shown only on failure, to stderr).
"""

