import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

FLASH_SIZE = 4 * 1024 * 1024
TABLE_OFFSET = 0x8000
TABLE_LEN = 0x100
# Pixelblaze v3's table (read out of the dump, see the docstring).
PB_OTADATA_0 = 0x0E000  # first entry of PB's otadata partition (0xE000/0x2000)
PB_OTADATA_1 = 0x0F000  # second entry
APP0 = 0x10000
APP1 = 0x150000
APP_LEN = 0x140000
PB_SPIFFS = 0x290000
# Luxel's 4 MB table (partitions.csv): the takeover installs it directly.
LXCF_OFFSET = 0x9000  # config.rs RECORD_OFFSET
LXDV_OFFSET = 0xA000  # config.rs DEV_OFFSET
DEV_VER = 8  # config.rs DEV_VER (v8 took a v7 pad byte for the data pin)
LXBG_OFFSET = 0xC000  # ota.rs GUARD_OFFSET (4th nvs sector under both layouts)
LUXEL_OTADATA = 0xD000  # partitions.csv: otadata, 0xd000, 0x2000
LUXEL_STORAGE = 0x290000  # partitions.csv: storage, 0x290000, 0x80000
SECTOR = 0x1000
ESP_OTA_IMG_VALID = 2

# What the fixture's config.json maps to (takeover.rs inherit_device +
# pbfs.rs).  The brightness is 1.0 × maxBrightness 0.5: 255 × 128 -> 128/255
# -> round(128 × 31 / 255) = 16/31.
PIXELS = 180
PROTO_CODE = 0          # sk9822 (leds::Protocol)
PROTO_NAME = "sk9822"
ORDER_CODE = 4          # PB "GRB" on an SK9822 (native bgr) -> Luxel "brg"
ORDER_NAME = "brg"
BRI_255, MAXBRI_255, EFF_255 = 255, 128, 128
BRIGHTNESS = 16
CAP_MA = 0
GAMMA_TENTHS = 0

# Any of these in the serial log means the takeover bailed out; fail fast
# rather than burning the full timeout waiting for a marker that won't come.
ABORT_MARKERS = (
    "takeover: verify failed at",
    "takeover: read failed at",
    "takeover: copy failed",
    "partitions: flash too small",
    "takeover: own image not found",
    "takeover: cannot size own image",
    "takeover: config wipe failed",
    "takeover: creds carry-over failed",
    "takeover: settings carry-over failed",
    "takeover: TABLE WRITE FAILED",
    "takeover: no ota_0 in embedded table",
    "consecutive failed boots — rolling back",
)

ABORT_HINTS = {
    "partitions: flash too small": (
        "this is a NEW QEMU divergence, not a firmware bug: esp-storage's "
        "FlashStorage::capacity() has previously reported the real 4 MiB "
        "under emulation.  Report it rather than working around it."
    ),
}

REBOOT_LINE = "takeover: partition table installed — rebooting into Luxel"
# Prefixes only — the rest of each line is the SSID, which never appears here.
INHERIT_PREFIX = 'takeover: inherited WiFi credentials for "'
KILL_PREFIX = 'wifi: creds from flash ("'
FORMAT_LINE = re.compile(r"patterns: format \d+ != \d+, wiping storage")
# Firmware lines that spell the SSID out; the failure-path serial tail cuts
# each at its prefix so the dump's real network name never reaches a log.
SECRET_PREFIXES = (INHERIT_PREFIX, KILL_PREFIX, 'wifi: joining "')


class Fail(Exception):
    pass


# --------------------------------------------------------------------------
# compose


def otadata_entry(seq: int) -> bytes:
    """One 32-byte ESP-IDF otadata entry selecting OTA slot `(seq - 1) % n`.

    Layout (`esp_ota_select_entry_t`): u32 seq, 20 bytes label, 4 bytes
    ota_state, u32 crc.  The CRC is over the 4 seq bytes only, zlib crc32 with
    an all-ones initial value (ESP-IDF `bootloader_common_ota_select_crc`).
    Unwritten fields stay erased (0xFF) exactly as esp_ota_set_boot_partition
    leaves them for a non-rollback build.
    """
    crc = zlib.crc32(struct.pack("<I", seq), 0xFFFFFFFF) & 0xFFFFFFFF
    return struct.pack("<I", seq) + b"\xff" * 24 + struct.pack("<I", crc)


def check_fixture(stock: bytes) -> None:
    """The dump has to be a Pixelblaze v3 flash image — sanity-check the
    bits this test's offsets are derived from, without touching NVS."""
    if len(stock) != FLASH_SIZE:
        raise Fail(f"--stock is {len(stock)} B, expected {FLASH_SIZE}")
    want = {
        b"nvs": (0x9000, 0x5000), b"otadata": (0xE000, 0x2000),
        b"app0": (APP0, APP_LEN), b"app1": (APP1, APP_LEN),
        b"spiffs": (PB_SPIFFS, 0x170000),
    }
    got = {}
    t = stock[TABLE_OFFSET : TABLE_OFFSET + TABLE_LEN]
    for i in range(0, TABLE_LEN, 32):
        e = t[i : i + 32]
        if e[:2] != b"\xaa\x50":
            break
        off, ln = struct.unpack_from("<II", e, 4)
        got[e[12:28].rstrip(b"\0")] = (off, ln)
    if got != want:
        raise Fail(f"--stock: not the Pixelblaze v3 table at 0x8000: {got}")
    if stock[APP1 : APP1 + 1] != b"\xe9":
        raise Fail("--stock: no app image in app1 — is this the stock PB dump?")
    if stock[PB_SPIFFS : PB_SPIFFS + SECTOR] == b"\xff" * SECTOR:
        raise Fail("--stock: spiffs at 0x290000 is erased — no config.json to inherit")


def compose(stock: bytes, ota: bytes, slot: str) -> bytearray:
    check_fixture(stock)
    if ota[:1] != b"\xe9":
        raise Fail("result/luxel-fw-ota.bin does not start with the 0xE9 image magic")
    if len(ota) > APP_LEN:
        raise Fail(f"the {len(ota)} B app image does not fit a {APP_LEN:#x} B PB slot")

    img = bytearray(stock)
    if slot == "app1":
        img[APP1 : APP1 + len(ota)] = ota
        # PB's first otadata entry (0xE000, seq=1) stays valid and untouched;
        # the higher sequence number in the second entry wins, so the stock
        # bootloader boots app1 — the dump already has this, rewrite it so
        # the test does not depend on the dump's history.
        img[PB_OTADATA_1 : PB_OTADATA_1 + 32] = otadata_entry(2)
    else:
        img[APP0 : APP0 + len(ota)] = ota
        # Select app0: entry #0 seq=1, entry #1 erased (the dump's seq=2
        # there would otherwise win).
        img[PB_OTADATA_0 : PB_OTADATA_0 + 32] = otadata_entry(1)
        img[PB_OTADATA_1 : PB_OTADATA_1 + SECTOR] = b"\xff" * SECTOR
    return img


